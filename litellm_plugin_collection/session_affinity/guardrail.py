"""OpenCode session affinity: supply a stable session id when the client omits one.

OpenCode Go rejects requests that do not carry ``x-opencode-session``. LiteLLM's
``opencode_go`` provider derives that header from the request's stable session id
(``litellm_session_id`` / ``metadata.session_id``), but harnesses other than
OpenCode often send no session id at all. This guardrail fills the gap with a
deterministic conversation fingerprint so those clients can reach OpenCode Go
through the gateway without a client-side change.

Ordering matters: this guardrail must run before the compression guardrails so
it reads the conversation before they rewrite it. It never overrides a session
id supplied by the caller (header, body metadata, or a non-generated
``litellm_session_id``).
"""

from __future__ import annotations

import hashlib
import re
from typing import Any

try:
    from litellm.integrations.custom_guardrail import CustomGuardrail
except Exception:  # pragma: no cover - litellm is a runtime dependency
    class CustomGuardrail:  # type: ignore[no-redef]
        pass


_ID_PREFIX = "oc-"
_ID_RE = re.compile(r"^[A-Za-z0-9_\-]{8,128}$")
_WHITESPACE_RE = re.compile(r"\s+")
_GENERATED_FLAG = "litellm_session_id_generated"
_EXISTING_HEADERS = (
    "x-litellm-session-id",
    "x-session-id",
    "x-opencode-session",
    "x-opencode-session-id",
    "session-id",
)
_METADATA_BUCKETS = ("metadata", "litellm_metadata")
_MAX_FINGERPRINT_CHARS = 65536


def _header(request_data: dict[str, Any], name: str) -> str | None:
    """Read a header from the flat request or the captured proxy request."""
    containers: list[Any] = [request_data, request_data.get("headers")]
    proxy_request = request_data.get("proxy_server_request")
    if isinstance(proxy_request, dict):
        containers.append(proxy_request.get("headers"))
    for container in containers:
        if not isinstance(container, dict):
            continue
        value = container.get(name)
        if not value:
            lowered = name.lower()
            for key, candidate in container.items():
                if isinstance(key, str) and key.lower() == lowered and candidate:
                    value = candidate
                    break
        if value:
            return str(value)
    return None


def _content_text(content: Any) -> str:
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for item in content:
            if isinstance(item, dict):
                if item.get("type") == "text":
                    parts.append(str(item.get("text", "")))
            elif isinstance(item, str):
                parts.append(item)
        return "\n".join(parts)
    return str(content) if content is not None else ""


def _first_text(messages: Any, role: str) -> str:
    if not isinstance(messages, list):
        return ""
    for message in messages:
        if not isinstance(message, dict) or message.get("role") != role:
            continue
        text = _content_text(message.get("content")).strip()
        if text:
            return text
    return ""


def _normalize(text: str) -> str:
    return _WHITESPACE_RE.sub(" ", text).strip()[: _MAX_FINGERPRINT_CHARS]


def _generated(request_data: dict[str, Any]) -> bool:
    for bucket_name in _METADATA_BUCKETS:
        bucket = request_data.get(bucket_name)
        if isinstance(bucket, dict) and bucket.get(_GENERATED_FLAG):
            return True
    return False


def _existing_session_id(request_data: dict[str, Any]) -> str | None:
    """Return a caller-supplied session id, ignoring ids generated by LiteLLM."""
    direct = request_data.get("litellm_session_id") or request_data.get("session_id")
    if direct and not _generated(request_data):
        return str(direct)
    for bucket_name in _METADATA_BUCKETS:
        bucket = request_data.get(bucket_name)
        if not isinstance(bucket, dict) or bucket.get(_GENERATED_FLAG):
            continue
        value = bucket.get("session_id") or bucket.get("user_api_key_session_id")
        if value:
            return str(value)
    for name in _EXISTING_HEADERS:
        value = _header(request_data, name)
        if value:
            return value
    return None


def _derive_session_id(request_data: dict[str, Any]) -> str | None:
    """Build a stable id from the request's conversation fingerprint.

    A ``prompt_cache_key`` supplied by the harness is already a per-session id,
    so prefer it. Otherwise hash the first user message (or the system prompt
    when there is none). Identical opening prompts collide by design; the value
    only needs to be stable within a conversation.
    """
    cache_key = request_data.get("prompt_cache_key")
    if isinstance(cache_key, str):
        cache_key = cache_key.strip()
        if _ID_RE.match(cache_key):
            return cache_key

    messages = request_data.get("messages")
    text = _first_text(messages, "user") or _first_text(messages, "system")
    if not text:
        return None
    digest = hashlib.sha256(_normalize(text).encode("utf-8", "replace")).hexdigest()
    return f"{_ID_PREFIX}{digest[:32]}"


class OpenCodeSessionAffinity(CustomGuardrail):
    """Fill ``litellm_session_id`` for clients that do not send one."""

    def __init__(self, guardrail_name: str | None = None, **kwargs: Any) -> None:
        self.guardrail_name = guardrail_name or "opencode-session-affinity"
        try:
            super().__init__(guardrail_name=self.guardrail_name, **kwargs)  # type: ignore[misc]
        except Exception:
            pass

    async def apply_guardrail(
        self,
        inputs: dict[str, Any],
        request_data: dict[str, Any],
        input_type: str,
        logging_obj: Any = None,
    ) -> dict[str, Any]:
        if input_type != "request" or not isinstance(request_data, dict):
            return inputs
        if _existing_session_id(request_data):
            return inputs

        session_id = _derive_session_id(request_data)
        if not session_id:
            return inputs

        request_data["litellm_session_id"] = session_id
        for bucket_name in _METADATA_BUCKETS:
            bucket = request_data.get(bucket_name)
            if not isinstance(bucket, dict):
                bucket = {}
                request_data[bucket_name] = bucket
            bucket["session_id"] = session_id
            bucket.pop(_GENERATED_FLAG, None)
        return inputs


opencode_session_affinity = OpenCodeSessionAffinity()
guardrail = opencode_session_affinity
